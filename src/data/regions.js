export function azOptionsForRegion(regionCode) {
  if (!regionCode) return [];
  const region = REGIONS.find((r) => r.code === regionCode);
  const count = region?.azCount || 3;
  return Array.from({ length: count }, (_, i) => `${regionCode}${String.fromCharCode(97 + i)}`);
}

export function getRegionMeta(code) {
  return REGIONS.find((r) => r.code === code);
}

